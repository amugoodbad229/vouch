"""The closed vocabulary, and the one rule that depends on it.

FalkorDB cannot tell a typo from an absence. Ask for a relationship type that
does not exist and you get zero rows, not an error -- and zero rows is exactly
the signal this project refuses on. A model-supplied label would therefore
produce a silent wrong answer that is indistinguishable from a real refusal.

So every label and relationship type that reaches Cypher is a member of the
enums below. They are never assembled from user text and never generated by the
model. A tool that needs a label takes it as a `Label` member, which is the
narrowest point at which the mistake can still be caught.

`TRAVERSAL_DEPTHS` exists for the same reason. FalkorDB will not accept a bound
parameter as a variable-length bound (`*1..$d` raises "Encountered unhandled
type in inlined properties" on both v4.22.0 and 6.0.1), so the one value that
must be spliced into query text is drawn from a four-element closed set. It is
the only non-parameter in this codebase.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Final

from pydantic_settings import BaseSettings, SettingsConfigDict


class Label(StrEnum):
    """Node labels. Closed: see the module docstring."""

    SERVICE = "Service"
    TEAM = "Team"
    PERSON = "Person"
    DOCUMENT = "Document"
    DECISION = "Decision"
    CHANGE = "Change"
    INCIDENT = "Incident"
    CLAIM = "Claim"
    EPISODE = "Episode"
    PROCEDURE = "Procedure"
    HANDOFF = "Handoff"
    ACTION = "Action"


class Rel(StrEnum):
    """Relationship types. Closed: see the module docstring."""

    # Structure.
    CALLS = "CALLS"
    """caller -> callee. Blast radius walks this backwards."""

    # Accountability.
    OWNS = "OWNS"
    """Team|Person -> Service. The *declared* owner."""
    TOUCHED = "TOUCHED"
    """Person -> Service, stamped by a Change|Document. The *effective* owner."""
    MEMBER_OF = "MEMBER_OF"

    # Evidence.
    WROTE = "WROTE"
    SUPPORTS = "SUPPORTS"
    """Decision -> Document."""
    SUPERSEDES = "SUPERSEDES"
    """Document -> Document. Makes invalidation a fact rather than a deletion."""
    ABOUT = "ABOUT"
    """Claim|Episode|Incident -> Service."""
    LEARNED_IN = "LEARNED_IN"
    CONTRADICTS = "CONTRADICTS"

    # Change and incident flow.
    AFFECTS = "AFFECTS"
    RESOLVES = "RESOLVES"
    CAUSED = "CAUSED"
    HANDED_TO = "HANDED_TO"


class Outcome(StrEnum):
    """Why a tool returned what it returned.

    The distinction between the middle two is the whole product. `NO_RELATION`
    is a real answer backed by the graph; `MISSING_SUBJECT` and
    `MISSING_SUPPORT` are refusals. Collapsing them is how an agent ends up
    confidently reporting that nothing depends on a service it has never heard
    of.
    """

    ANSWERED = "answered"
    """Subject present, relation present, evidence supports the claim."""

    NO_RELATION = "no_relation"
    """Subject present, relation genuinely absent. A positive answer."""

    MISSING_SUBJECT = "missing_subject"
    """The thing asked about is not in the graph. Refuse."""

    MISSING_SUPPORT = "missing_support"
    """The relation exists but no evidence backs the claim. Refuse."""

    @property
    def is_refusal(self) -> bool:
        return self in (Outcome.MISSING_SUBJECT, Outcome.MISSING_SUPPORT)


TRAVERSAL_DEPTHS: Final[frozenset[int]] = frozenset({1, 2, 3, 4})
"""The only values ever spliced into query text. See the module docstring."""


def checked_depth(depth: int) -> int:
    """Return `depth` if it is in the closed set, else raise.

    Raising here is the point: a bad depth must fail loudly at the boundary
    rather than quietly become a traversal that matches nothing.
    """
    if depth not in TRAVERSAL_DEPTHS:
        raise ValueError(
            f"depth must be one of {sorted(TRAVERSAL_DEPTHS)}, got {depth!r}. "
            "FalkorDB cannot take a bound parameter as a variable-length bound, so "
            "this is a closed set rather than an arbitrary integer."
        )
    return depth


class Settings(BaseSettings):
    falkordb_host: str = "127.0.0.1"
    falkordb_port: int = 6379

    # The engine has no password in local development. It is bound to loopback
    # in docker-compose.yml precisely because of that.
    falkordb_username: str | None = None
    falkordb_password: str | None = None

    # Kept small and explicit: this graph is tiny, and a large pool would only
    # hide a connection leak.
    max_connections: int = 32
    query_timeout_ms: int = 5_000

    # The demo tenant. A second tenant, `beta`, exists to prove isolation.
    default_tenant: str = "acme"

    # Where the approval ledger lives. SQLite because the gate needs to survive a
    # restart and does not need to be a service; the file is gitignored.
    ledger_path: str = ".artifacts/approvals.db"

    # The real action adapter is used only when both of these are set, and
    # `/api/health` reports which adapter is live so a mock run says so on screen.
    issue_repo: str | None = None
    github_token: str | None = None

    model_config = SettingsConfigDict(env_file=".env", extra="ignore")


settings = Settings()
